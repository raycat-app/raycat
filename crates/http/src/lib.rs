//! Минимальный блокирующий HTTP/1.1-клиент.
//!
//! Почему не `ureq` и не `reqwest`: чтобы запрос был байт в байт как у настоящего
//! приложения, нужен полный контроль над заголовками (порядок и регистр у разных
//! клиентов разные), а готовые клиенты приводят их к нижнему регистру, сами
//! переставляют и добавляют свои. Нужное подмножество протокола (одно соединение —
//! один запрос, тело по `Content-Length`, chunked или до закрытия, gzip, deflate, br,
//! zstd) небольшое, поэтому клиент свой.
//!
//! Вызывающий код передаёт полный упорядоченный список заголовков, включая `Host`;
//! клиент не добавляет ничего, кроме `Content-Length` для запроса с телом.
//! Редиректы клиент не выполняет: это делает вызывающий код (см. [`Url::join`]).
//!
//! Сервер недоверенный: каждая строка, блок заголовков, чанк, трейлеры и распакованное
//! тело ограничены по размеру, а весь обмен ограничен общим сроком, чтобы сервер,
//! присылающий по байту за тайм-аут бездействия, не занял процесс навсегда.

